import Foundation
import Testing
@testable import UniConnectTranscriptRetention

/// `recent-prompts.v1`: the time of the last thing the person wrote, from sample transcripts.
@Suite struct TranscriptLastPromptTests {
    private static let claude = """
    {"type":"user","message":{"role":"user","content":"arregla el login"},"timestamp":"2026-11-08T10:00:00.000Z"}
    {"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Hecho"}]},"timestamp":"2026-11-08T10:00:05.000Z"}
    {"type":"user","message":{"role":"user","content":[{"type":"text","text":"y ahora los tests"}]},"timestamp":"2026-11-08T10:05:00.000Z"}
    {"type":"assistant","message":{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Bash"}]},"timestamp":"2026-11-08T10:05:02.000Z"}
    {"type":"user","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]},"timestamp":"2026-11-08T10:05:09.000Z"}
    {"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>"},"timestamp":"2026-11-08T10:06:00.000Z"}
    {"type":"user","message":{"role":"user","content":"<local-command-stdout></local-command-stdout>"},"timestamp":"2026-11-08T10:06:01.000Z"}
    {"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: The messages below were generated by the user while running local commands."},"timestamp":"2026-11-08T10:06:02.000Z"}
    {"type":"user","isSidechain":true,"message":{"role":"user","content":"subagente"},"timestamp":"2026-11-08T10:07:00.000Z"}
    """

    private static let codex = """
    {"timestamp":"2026-11-08T09:00:00.000Z","type":"session_meta","payload":{"id":"x"}}
    {"timestamp":"2026-11-08T09:01:00.000Z","type":"event_msg","payload":{"type":"user_message","message":"revisa el diff"}}
    {"timestamp":"2026-11-08T09:01:30.000Z","type":"response_item","payload":{"type":"message","role":"user","content":[{"type":"input_text","text":"<environment_context>"}]}}
    {"timestamp":"2026-11-08T09:02:00.000Z","type":"event_msg","payload":{"type":"agent_message","message":"listo"}}
    """

    private func date(_ stamp: String) -> Date {
        let formatter = ISO8601DateFormatter()
        formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        return formatter.date(from: stamp)!
    }

    @Test("Claude: the last typed prompt, ignoring tool results, internal commands, meta and sidechains")
    func claudeLastPrompt() {
        let reader = TranscriptLastPrompt(provider: .claude)
        #expect(reader.lastPromptDate(inLines: Data(Self.claude.utf8)) == date("2026-11-08T10:05:00.000Z"))
    }

    @Test("Codex: the last user_message of the rollout")
    func codexLastPrompt() {
        let reader = TranscriptLastPrompt(provider: .codex)
        #expect(reader.lastPromptDate(inLines: Data(Self.codex.utf8)) == date("2026-11-08T09:01:00.000Z"))
    }

    @Test("No prompt, no conversation or no file: nil")
    func nothingToReport() throws {
        let reader = TranscriptLastPrompt(provider: .claude)
        #expect(reader.lastPromptDate(inLines: Data()) == nil)
        let onlyAgent = #"{"type":"assistant","message":{"role":"assistant","content":"hola"},"timestamp":"2026-11-08T10:00:00Z"}"#
        #expect(reader.lastPromptDate(inLines: Data(onlyAgent.utf8)) == nil)
        let missing = FileManager.default.temporaryDirectory.appendingPathComponent("no-\(UUID().uuidString).jsonl")
        #expect(reader.lastPromptDate(inFileAt: missing) == nil)
    }

    @Test("Only the tail is read; a cut first line is skipped and the tail grows until a prompt")
    func readsTheTail() throws {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("tail-\(UUID().uuidString).jsonl")
        defer { try? FileManager.default.removeItem(at: url) }
        let filler = (0..<2_000).map { index in
            #"{"type":"assistant","message":{"role":"assistant","content":"relleno \#(index) \#(String(repeating: "x", count: 80))"},"timestamp":"2026-11-08T11:00:00Z"}"#
        }.joined(separator: "\n")
        let text = #"{"type":"user","message":{"role":"user","content":"el primero"},"timestamp":"2026-11-08T08:00:00Z"}"# + "\n" + filler + "\n"
        try Data(text.utf8).write(to: url)
        // The prompt sits ~200 KB before the end: beyond the first 64 KiB window, within the cap.
        #expect(TranscriptLastPrompt(provider: .claude).lastPromptDate(inFileAt: url) == ISO8601DateFormatter().date(from: "2026-11-08T08:00:00Z"))
        // With a cap smaller than the distance, nothing is invented.
        #expect(TranscriptLastPrompt(provider: .claude, maximumTailBytes: 64 * 1_024).lastPromptDate(inFileAt: url) == nil)
    }
}
