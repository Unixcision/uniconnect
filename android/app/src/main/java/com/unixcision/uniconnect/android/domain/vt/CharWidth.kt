package com.unixcision.uniconnect.android.domain.vt

/** Terminal cell width of a code point: 0 for combining marks, 2 for East Asian wide and emoji, else 1. */
object CharWidth {
    private val zero = listOf(0x0300..0x036F, 0x0483..0x0489, 0x0591..0x05BD, 0x0610..0x061A, 0x064B..0x065F, 0x200B..0x200F,
        0x20D0..0x20FF, 0xFE00..0xFE0F, 0xFE20..0xFE2F, 0x1F3FB..0x1F3FF, 0xE0100..0xE01EF)
    private val wide = listOf(0x1100..0x115F, 0x231A..0x231B, 0x2329..0x232A, 0x23E9..0x23EC, 0x25FD..0x25FE, 0x2614..0x2615,
        0x2648..0x2653, 0x26AA..0x26AB, 0x26BD..0x26BE, 0x26C4..0x26C5, 0x2700..0x27BF, 0x2E80..0x303E, 0x3041..0x33FF,
        0x3400..0x4DBF, 0x4E00..0x9FFF, 0xA000..0xA4CF, 0xAC00..0xD7A3, 0xF900..0xFAFF, 0xFE30..0xFE4F, 0xFF00..0xFF60,
        0xFFE0..0xFFE6, 0x1F004..0x1F004, 0x1F0CF..0x1F0CF, 0x1F18E..0x1F18E, 0x1F191..0x1F19A, 0x1F300..0x1F64F,
        0x1F680..0x1F6FF, 0x1F900..0x1F9FF, 0x1FA70..0x1FAFF, 0x20000..0x3FFFD)

    fun of(codePoint: Int): Int = when {
        codePoint < 0x20 || codePoint in 0x7F..0x9F -> 0
        zero.any { codePoint in it } -> 0
        wide.any { codePoint in it } -> 2
        else -> 1
    }
}
